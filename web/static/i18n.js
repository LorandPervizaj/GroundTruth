  function readCookie() {
    const match = document.cookie.match(new RegExp(`(?:^|; )${COOKIE}=([^;]*)`));
    return match ? decodeURIComponent(match[1]) : null;
  }

  function writeCookie(lang) {
    document.cookie = `${COOKIE}=${encodeURIComponent(lang)}; path=/; SameSite=Lax`;
  }

  function getLang() {
    const stored = readCookie();
    if (stored === "sq" || stored === "en") return stored;
    return DEFAULT;
  }

  let currentLang = getLang();

  function interpolate(text, vars) {
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : `{${k}}`));
  }

  function t(key, vars) {
    const pack = STRINGS[currentLang] || STRINGS[DEFAULT];
    const fallback = STRINGS.en[key] || key;
    return interpolate(pack[key] ?? fallback, vars);
  }

  function translateConfidence(level) {
    const key = String(level || "").toLowerCase();
    const map = {
      high: t("conf_high"),
      medium: t("conf_medium"),
      low: t("conf_low"),
      insufficient: t("conf_insufficient"),
    };
    return map[key] || level;
  }

  function apply() {
    document.documentElement.lang = currentLang === "sq" ? "sq" : "en";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const text = t(el.getAttribute("data-i18n"));
      const tip = el.querySelector(":scope > .info-tip");
      if (tip) {
        let label = el.querySelector(":scope > .section-title-label");
        if (!label) {
          label = document.createElement("span");
          label.className = "section-title-label";
          el.insertBefore(label, tip);
        }
        label.textContent = text;
        el.classList.add("section-title-with-info");
      } else {
        el.textContent = text;
      }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      document.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll(".info-tip[data-i18n-tip]").forEach((el) => {
      const key = el.getAttribute("data-i18n-tip");
      if (!key) return;
      let vars = undefined;
      const rawVars = el.getAttribute("data-i18n-tip-vars");
      if (rawVars) {
        try {
          vars = JSON.parse(rawVars);
        } catch {
          vars = undefined;
        }
      }
      if (window.MetrikSite?.setInfoTipText) {
        window.MetrikSite.setInfoTipText(el, t(key, vars));
      } else {
        const bubble = el.querySelector(".info-tip__bubble");
        if (bubble) bubble.textContent = t(key, vars);
        el.setAttribute("aria-label", t("info_tip_label"));
      }
    });
    const titleKey = document.body?.dataset?.pageTitle;
    if (titleKey) document.title = t(titleKey);
  }

  function setLang(lang) {
    if (lang !== "sq" && lang !== "en") return;
    currentLang = lang;
    writeCookie(lang);
    fetch("/api/lang", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ lang }),
    }).catch(() => {});
    apply();
    document.dispatchEvent(new CustomEvent("metrik:langchange", { detail: { lang } }));
  }

  window.MetrikI18n = {
    t,
    getLang,
    setLang,
    apply,
    translateConfidence,
    COOKIE,
  };

  apply();
